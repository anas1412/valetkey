import { useEffect, useState, type FormEvent } from 'react'
import { Sheet, SheetContent, SheetHeader, SheetTitle, SheetDescription, SheetBody, SheetFooter } from '@/components/ui/sheet'
import { Form, FormItem, FormLabel, FormControl, FormDescription, FormMessage, Input } from '@/components/ui/form'
import { Combobox } from '@/components/ui/combobox'
import { LiquidToggle } from '@/components/ui/liquid-toggle'
import { Button } from '@/components/ui/button'
import { ModelPicker } from '@/components/ModelPicker'
import { ChipInput, validateCIDR } from '@/components/ChipInput'
import { api } from '@/lib/api'
import { useToast } from '@/lib/toast'
import type { Group, ProxyKey, ProxyKeySpec } from '@/lib/types'

interface Draft {
  tenant: string
  name: string
  anyModel: boolean
  models: string[]
  subnets: string[]
  rpm: string
  tpm: string
  enabled: boolean
}

function toDraft(k?: ProxyKey): Draft {
  return {
    tenant: k?.namespace ?? '',
    name: k?.name ?? '',
    anyModel: !k?.spec.models?.length,
    models: k?.spec.models ?? [],
    subnets: k?.spec.subnets ?? [],
    rpm: k?.spec.rpm ? String(k.spec.rpm) : '',
    tpm: k?.spec.tpm ? String(k.spec.tpm) : '',
    enabled: (k?.spec.status ?? 'Enabled') === 'Enabled',
  }
}

/** Create or edit an API key (ProxyKey). The key itself is generated by LLMP. */
export function KeySheet({ open, apiKey, groups, onClose, onSaved }: {
  open: boolean
  apiKey?: ProxyKey
  groups: Group[]
  onClose: () => void
  onSaved: () => void
}) {
  const editing = !!apiKey
  const [d, setD] = useState<Draft>(() => toDraft(apiKey))
  const [error, setError] = useState<string>()
  const [busy, setBusy] = useState(false)
  const [available, setAvailable] = useState<string[]>([])
  const [loadingModels, setLoadingModels] = useState(false)
  const [modelsError, setModelsError] = useState<string>()
  const notify = useToast()
  const set = <K extends keyof Draft>(k: K, v: Draft[K]) => setD((prev) => ({ ...prev, [k]: v }))

  useEffect(() => {
    if (open) {
      setD(toDraft(apiKey))
      setError(undefined)
    }
  }, [open, apiKey])

  // Load the models this tenant's providers offer whenever the tenant changes.
  useEffect(() => {
    if (!open || !d.tenant) return setAvailable([])
    let cancelled = false
    setLoadingModels(true)
    setModelsError(undefined)
    api.groupModels(d.tenant)
      .then(({ models }) => { if (!cancelled) setAvailable([...new Set([...(models ?? []), ...d.models])].sort()) })
      .catch((err) => { if (!cancelled) setModelsError((err as Error).message) })
      .finally(() => { if (!cancelled) setLoadingModels(false) })
    return () => { cancelled = true }
    // eslint-disable-next-line react-hooks/exhaustive-deps -- reload only when the tenant changes
  }, [open, d.tenant])

  const submit = async (e: FormEvent) => {
    e.preventDefault()
    if (!d.tenant) return setError('Pick a tenant')
    if (!d.name) return setError('Name the key, e.g. after the app that uses it')
    if (!d.anyModel && !d.models.length) return setError('Select at least one model, or allow all models')
    const spec: ProxyKeySpec = {
      status: d.enabled ? 'Enabled' : 'Disabled',
      models: d.anyModel ? [] : d.models,
      subnets: d.subnets,
      rpm: Number(d.rpm) || undefined,
      tpm: Number(d.tpm) || undefined,
    }
    setBusy(true)
    setError(undefined)
    try {
      if (editing) await api.updateKey(apiKey.namespace, apiKey.name, spec)
      else await api.createKey(d.tenant, d.name.trim(), spec)
      notify(editing ? 'Key updated' : 'Key created', {
        description: editing ? `${d.tenant}/${d.name}` : 'Open it in the list to copy the key and usage examples.',
      })
      onSaved()
      onClose()
    } catch (err) {
      setError((err as Error).message)
      notify('Could not save', { description: (err as Error).message, variant: 'error' })
    } finally {
      setBusy(false)
    }
  }

  return (
    <Sheet open={open} onOpenChange={(o) => !o && onClose()}>
      <SheetContent side="right" className="sm:max-w-lg">
        <Form onSubmit={submit} className="flex flex-col h-full">
          <SheetHeader>
            <SheetTitle>{editing ? `Edit ${apiKey.name}` : 'Create an API key'}</SheetTitle>
            <SheetDescription>LLMP generates the key and stores it as a Secret in the tenant's namespace.</SheetDescription>
          </SheetHeader>

          <SheetBody className="space-y-5 overflow-y-auto">
            <FormItem>
              <FormLabel required>Tenant</FormLabel>
              {editing ? (
                <FormControl><Input value={d.tenant} disabled /></FormControl>
              ) : groups.length ? (
                <Combobox
                  options={groups.map((g) => ({ value: g.name, label: g.name, description: g.spec.channelRefs.join(', ') }))}
                  value={d.tenant || null}
                  onValueChange={(v) => set('tenant', v ?? '')}
                  placeholder="Pick a tenant"
                  searchPlaceholder="Search tenants…"
                />
              ) : (
                <p className="text-sm text-text-muted">Create a tenant first.</p>
              )}
            </FormItem>

            <FormItem>
              <FormLabel required>Name</FormLabel>
              <FormControl>
                <Input value={d.name} disabled={editing} placeholder="billing-service" onChange={(e) => set('name', e.target.value.toLowerCase())} />
              </FormControl>
              <FormDescription>Lowercase letters, digits and "-". Usually the app that will use it.</FormDescription>
            </FormItem>

            <FormItem>
              <div className="flex items-center justify-between gap-3">
                <div>
                  <FormLabel>Allowed models</FormLabel>
                  <FormDescription>{d.anyModel ? "Every model the tenant's providers offer." : 'Only the selected models.'}</FormDescription>
                </div>
                <div className="flex items-center gap-2 shrink-0">
                  <span className="text-xs text-text-muted">All models</span>
                  <LiquidToggle value={d.anyModel} onChange={(v) => set('anyModel', v)} />
                </div>
              </div>
              {!d.anyModel && (
                <ModelPicker
                  available={available}
                  selected={d.models}
                  onChange={(m) => set('models', m)}
                  loading={loadingModels}
                  error={modelsError}
                  emptyHint={d.tenant ? "This tenant's providers list no models." : 'Pick a tenant first.'}
                />
              )}
            </FormItem>

            <FormItem>
              <FormLabel>Allowed IP ranges</FormLabel>
              <ChipInput values={d.subnets} onChange={(v) => set('subnets', v)} placeholder="10.0.0.0/8 or 2001:db8::/32" validate={validateCIDR} />
              <FormDescription>Press Enter after each one. None = any address.</FormDescription>
            </FormItem>

            <div className="grid grid-cols-2 gap-4">
              <FormItem>
                <FormLabel>Requests / min</FormLabel>
                <FormControl><Input type="number" min={0} value={d.rpm} placeholder="unlimited" onChange={(e) => set('rpm', e.target.value)} /></FormControl>
              </FormItem>
              <FormItem>
                <FormLabel>Tokens / min</FormLabel>
                <FormControl><Input type="number" min={0} value={d.tpm} placeholder="unlimited" onChange={(e) => set('tpm', e.target.value)} /></FormControl>
              </FormItem>
            </div>

            <div className="flex items-center justify-between rounded-lg border border-border p-3">
              <div>
                <div className="text-sm font-medium text-text-primary">Key enabled</div>
                <div className="text-xs text-text-muted">Turn off to block the key without deleting it.</div>
              </div>
              <LiquidToggle value={d.enabled} onChange={(v) => set('enabled', v)} />
            </div>

          </SheetBody>

          <SheetFooter className="flex-col items-stretch gap-2">
            <FormMessage error={error} />
            <div className="flex justify-end gap-2">
              <Button type="button" variant="ghost" onClick={onClose}>Cancel</Button>
              <Button type="submit" variant="primary" isLoading={busy} loadingText="Saving…" disabled={!editing && !groups.length}>
                {editing ? 'Save changes' : 'Create key'}
              </Button>
            </div>
          </SheetFooter>
        </Form>
      </SheetContent>
    </Sheet>
  )
}
